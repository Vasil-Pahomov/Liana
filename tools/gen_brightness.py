"""Gamma table of the strip (src/brightness.h).

The table maps a logical 0..255 channel value to the PWM value sent to the LEDs so that
brightness steps look even to the eye. It was originally computed in Brightness.xlsx;
the curve is an exponential

    BRI[i] = round(255 * (exp(K * i / 255) - 1) / (exp(K) - 1)),  K = 3.95

which reproduces the committed table within +-1 (21 of 256 entries differ by one).
The committed table stays the source of truth; this script checks it, or regenerates it with --write.

Usage:
    python tools/gen_brightness.py            # compare the formula with src/brightness.h
    python tools/gen_brightness.py --write    # overwrite src/brightness.h with the formula
"""
import math
import os
import re
import sys

K = 3.95
HEADER = os.path.join(os.path.dirname(__file__), "..", "src", "brightness.h")


def formula(i):
    return int(math.floor(255 * (math.exp(K * i / 255) - 1) / (math.exp(K) - 1) + 0.5))


def read_table(path):
    text = open(path, encoding="utf-8").read()
    body = text.split("BRI[]")[1]
    return [int(x) for x in re.findall(r"\b(\d+)\b", body)]


def write_table(path, values):
    lines = ["#ifndef BRIGHTNESS_H", "#define BRIGHTNESS_H",
             "// generated by tools/gen_brightness.py, K = %s" % K,
             "const byte PROGMEM BRI[] = {"]
    lines += ["    %d," % v for v in values[:-1]]
    lines += ["    %d" % values[-1], "};", "", "#endif", ""]
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def main():
    generated = [formula(i) for i in range(256)]
    if "--write" in sys.argv:
        write_table(HEADER, generated)
        print("written", HEADER)
        return 0
    current = read_table(HEADER)
    if len(current) != 256:
        print("unexpected table size", len(current))
        return 1
    diffs = [(i, c, g) for i, (c, g) in enumerate(zip(current, generated)) if c != g]
    print("entries differing from the formula: %d, max deviation: %d"
          % (len(diffs), max((abs(c - g) for _, c, g in diffs), default=0)))
    for i, c, g in diffs[:10]:
        print("  BRI[%d] = %d, formula gives %d" % (i, c, g))
    return 0


if __name__ == "__main__":
    sys.exit(main())
